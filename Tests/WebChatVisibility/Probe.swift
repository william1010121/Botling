// Isolated native SwiftUI/WebKit regression; synthetic data and fresh added-account stores only.
import AppKit
import SwiftUI
import WebKit
import ClaudeCodeBotCore
@testable import ClaudeCodeBot

@MainActor
func require(_ value: @autoclosure () -> Bool, _ message: String) throws {
    if !value() { throw NSError(domain: "WebChatVisibility", code: 1, userInfo: [NSLocalizedDescriptionKey: message]) }
}

struct FixturePages: NSViewRepresentable {
    let views: [WKWebView]
    func makeNSView(context: Context) -> NSView { NSView() }
    func updateNSView(_ container: NSView, context: Context) {
        for view in views where view.superview !== container {
            view.frame = container.bounds
            view.autoresizingMask = [.width, .height]
            container.addSubview(view)
        }
    }
}

@MainActor
func run() async throws {
    let out = URL(filePath: CommandLine.arguments[1])
    try FileManager.default.createDirectory(at: out, withIntermediateDirectories: true)
    let root = FileManager.default.temporaryDirectory.appending(path: "ccb-web-native-\(UUID())")
    let workspace = Workspace(root: root) { profile, store in Bot(profile: profile, launcher: { _ in throw NSError(domain: "FixtureNoAgent", code: 1) }, store: store) }
    let shelf = workspace.web
    let site = WebSite.gemini
    let personal = shelf.addAccount(on: site, name: "SAMPLE Personal")
    let work = shelf.addAccount(on: site, name: "SAMPLE Work")
    let accounts = [personal, work]
    var sessions: [WebSession] = []
    var views: [WKWebView] = []
    var checks: [String: Bool] = [:]
    for (i, account) in accounts.enumerated() {
        workspace.navigate(to: site, account: account)
        shelf.handled(site)
        let session = WebSession.session(for: site, shelf: shelf)
        sessions.append(session)
        let view = session.front.webView
        views.append(view)
        let cookie = HTTPCookie(properties: [.domain: "fixture.local", .path: "/", .name: "synthetic-account", .value: account.id, .secure: "TRUE"])!
        await view.configuration.websiteDataStore.httpCookieStore.setCookie(cookie)
        // Load no remote URL. Persistent stores are new UUIDs generated by addAccount.
        view.loadHTMLString("""
        <!doctype html><meta charset="utf-8"><style>body{background:#17171c;color:#eee;font:18px system-ui;padding:32px}small{color:#aaa}</style>
        <small>SYNTHETIC DATA · isolated WKWebView · no sign-in</small><h2>\(account.name)</h2>
        <p>Reply is generating locally: <b id="count">0</b></p>
        <script>window.fixtureToken='\(account.id)';window.ticks=0;setInterval(()=>document.querySelector('#count').textContent=++window.ticks,50)</script>
        """, baseURL: nil)
        for _ in 0..<150 {
            if (try? await view.evaluateJavaScript("window.fixtureToken")) as? String == account.id { break }
            try await Task.sleep(for: .milliseconds(20))
        }
        shelf.bringToFront(session.front.id, on: site)
        shelf.record(on: site, page: session.front.id, url: site.conversationURL("sample\(i)1234"), pageTitle: nil,
                     reading: .read(title: account.name, turns: [WebTurn(role: .user, text: "Keep my current question")] + (i == 1 ? [WebTurn(role: .assistant, text: "Current answer")] : [])), settled: i == 1)
    }
    // Pin both account rows before navigating; exercise pin + visibility on real sessions.
    for i in accounts.indices {
        let row = shelf.conversation("sample\(i)1234", of: site)!
        shelf.setPinned(true, conversation: row, of: site)
    }
    checks["bothAccountPinsVisibleWhenShortened"] = shelf.listed(of: site, limit: 1).filter(\.isPinned).count == 2
    // Show the real sidebar, then invoke the same navigation callback as its provider rows.
    let content = HStack(spacing: 0) {
        VStack(alignment: .leading, spacing: 0) {
            Text("SYNTHETIC DATA · navigation regression").font(.system(size: 10)).foregroundStyle(.orange).padding(10)
            WebRailSection(workspace: workspace)
            Spacer()
        }.frame(width: 280).padding(8).background(Theme.side)
        VStack(alignment: .leading, spacing: 12) {
            Text("Provider reselect / account round trip").font(.title2)
            Text("Same production sidebar and navigation. Local fixture, no authenticated website.").foregroundStyle(.secondary)
            Text("Expected: SAMPLE Work remains visible and selected after clicking Gemini.")
            FixturePages(views: views).frame(height: 240)
            Spacer()
        }.padding(24).frame(maxWidth: .infinity, maxHeight: .infinity).background(Theme.ground)
    }.foregroundStyle(Theme.text).preferredColorScheme(.dark)
    let window = HeadlessRun.offscreenWindow(NSRect(x: 0, y: 0, width: 980, height: 620))
    window.appearance = NSAppearance(named: .darkAqua)
    let host = NSHostingView(rootView: content)
    host.frame = NSRect(x: 0, y: 0, width: 980, height: 620)
    window.contentView = host
    func snapshot(_ name: String) throws {
        host.layoutSubtreeIfNeeded()
        guard let rep = host.bitmapImageRepForCachingDisplay(in: host.bounds) else { return }
        host.cacheDisplay(in: host.bounds, to: rep)
        try rep.representation(using: .png, properties: [:])!.write(to: out.appending(path: name))
    }
    try await Task.sleep(for: .milliseconds(400))
    try snapshot("initial.png")
    workspace.navigate(to: site)
    try await Task.sleep(for: .milliseconds(200))
    try snapshot("reselected.png")
    checks["providerRetainsSelection"] = shelf.open[site.id] == "sample11234"
    checks["providerQueuesNoLoad"] = shelf.requested[site.id] == nil
    // Avoid actually consuming a broken baseline's unwanted remote start-page request.
    shelf.handled(site)
    let frontBeforePin = shelf.front, requestBeforePin = shelf.requested, openBeforePin = shelf.open
    let workRow = shelf.conversation("sample11234", of: site)!
    shelf.setPinned(false, conversation: workRow, of: site)
    shelf.setPinned(true, conversation: workRow, of: site)
    checks["pinToggleKeepsNavigation"] = shelf.front == frontBeforePin && shelf.requested == requestBeforePin && shelf.open == openBeforePin
    checks["pinToggleKeepsWorkAccount"] = shelf.account(of: site) == work
    for (i, account) in accounts.enumerated() {
        workspace.navigate(to: site, account: account)
        checks["account\(i)RestoresSelection"] = shelf.open[site.id] == "sample\(i)1234"
        checks["account\(i)QueuesNoLoad"] = shelf.requested[site.id] == nil
        shelf.handled(site)
        let session = WebSession.session(for: site, shelf: shelf)
        session.loadIfNeeded()
        checks["account\(i)KeepsSession"] = session === sessions[i]
        checks["account\(i)KeepsWebView"] = session.front.webView === views[i]
        checks["account\(i)KeepsProfile"] = session.front.webView.configuration.websiteDataStore.identifier == account.dataStoreID
        let cookies = await views[i].configuration.websiteDataStore.httpCookieStore.allCookies()
        checks["account\(i)KeepsOwnCookie"] = cookies.contains { $0.name == "synthetic-account" && $0.value == account.id }
        checks["account\(i)HasNoOtherAccountsCookie"] = !cookies.contains { $0.name == "synthetic-account" && $0.value != account.id }
        checks["account\(i)KeepsDocument"] = (try? await views[i].evaluateJavaScript("window.fixtureToken")) as? String == account.id
        let before = (try? await views[i].evaluateJavaScript("window.ticks")) as? Int ?? -1
        var after = before
        for _ in 0..<100 where after <= before {
            try await Task.sleep(for: .milliseconds(50))
            after = (try? await views[i].evaluateJavaScript("window.ticks")) as? Int ?? -1
        }
        checks["account\(i)GenerationContinues"] = before >= 0 && after > before
    }
    try JSONSerialization.data(withJSONObject: checks, options: [.prettyPrinted, .sortedKeys]).write(to: out.appending(path: "native-checks.json"))
    for key in checks.keys.sorted() { print("\(key): \(checks[key]! ? "PASS" : "FAIL")") }
    for account in accounts { WebSession.remove(account, of: site) }
    try await Task.sleep(for: .seconds(2))
    try require(checks.values.allSatisfy { $0 }, "Native navigation regression failed")
}

let app = NSApplication.shared
app.setActivationPolicy(.prohibited)
Task { @MainActor in
    do { try await run(); exit(0) } catch { fputs("\(error)\n", stderr); exit(1) }
}
app.run()
