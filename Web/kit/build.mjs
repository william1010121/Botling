// The component kit's build (see README.md): `node Web/kit/build.mjs` bundles src/ (Preact,
// hooks and htm from vendor/, the blocks, their CSS and the design tokens) into generated/kit.v1.js,
// and writes generated/kit-v1.ts, the same text as a string that Web/src/components.ts puts into a
// component's page. Both are committed (the app builds import them; Web/test/kit-build.test.ts checks
// they are fresh). Also `inlineTokens`, which the app builds use to put Web/src/tokens.css in
// place of a stylesheet's `@import "…/tokens.css";`.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const tokensImport = /^@import "([^"]*tokens\.css)";[ \t]*\r?\n?/m;

/** `css` (read from `from`) with its `@import "…/tokens.css";` line replaced by that file's text. */
export function inlineTokens(css, from) {
  const match = css.match(tokensImport);
  if (!match) return css;
  const tokens = readFileSync(resolve(dirname(from), match[1]), "utf8");
  return css.replace(tokensImport, () => (tokens.endsWith("\n") ? tokens : tokens + "\n"));
}

const vendor = { preact: "vendor/preact.module.js", "preact/hooks": "vendor/hooks.module.js", htm: "vendor/htm.module.js" };

/**
 * Builds the kit. Returns its text (`js`), the TypeScript module holding it (`module`), its size,
 * and whether generated/ already holds exactly this (`fresh`); `write` puts it into generated/.
 */
export async function buildKit({ write = false } = {}) {
  const { build, transform } = await import("esbuild");
  const result = await build({
    entryPoints: [join(here, "src/index.js")],
    bundle: true,
    format: "iife",
    // WKWebView on macOS 14 (1.x) and Electron's Chromium (2.x).
    target: ["safari17", "chrome130"],
    minify: true,
    legalComments: "inline",
    write: false,
    charset: "utf8",
    plugins: [{
      name: "kit",
      setup(b) {
        b.onResolve({ filter: /^(preact|preact\/hooks|htm)$/ }, (args) => ({ path: join(here, vendor[args.path]) }));
        // Stylesheets come in as minified text, inserted by src/index.js.
        b.onLoad({ filter: /\.css$/ }, async (args) => {
          const css = (await transform(readFileSync(args.path, "utf8"), { loader: "css", minify: true, target: ["safari17", "chrome130"] })).code;
          return { contents: `export default ${JSON.stringify(css.trim())};`, loader: "js" };
        });
      },
    }],
  });
  let js = result.outputFiles[0].text;
  // The kit goes into a page inside <script>…</script>: nothing in it may end that early.
  js = js.replace(/<\/(script)/gi, "<\\/$1").replace(/<!--/g, "<\\!--");
  const module = `// Generated by Web/kit/build.mjs from Web/kit/src: do not edit. The component kit v1, as the\n// text Web/src/components.ts puts into a component's page (<meta name="ccb-kit" content="1">).\nexport const kitV1: string = ${JSON.stringify(js)};\n`;
  const dist = join(here, "generated");
  const same = (name, text) => existsSync(join(dist, name)) && readFileSync(join(dist, name), "utf8") === text;
  const fresh = same("kit.v1.js", js) && same("kit-v1.ts", module);
  if (write && !fresh) {
    mkdirSync(dist, { recursive: true });
    writeFileSync(join(dist, "kit.v1.js"), js);
    writeFileSync(join(dist, "kit-v1.ts"), module);
  }
  return { js, module, bytes: Buffer.byteLength(js), fresh };
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const { bytes, fresh } = await buildKit({ write: true });
  console.log(`kit.v1.js: ${(bytes / 1024).toFixed(1)} KB${fresh ? " (unchanged)" : ""}`);
}
