import { afterEach, expect, it, vi } from 'vitest';
import { Composer } from '../src/composer';
import { setComposerHost } from '../src/composer-host';
import type { ChatState } from '../src/types';
let composer: Composer;
afterEach(()=> { composer?.view.destroy(); setComposerHost(null); document.body.replaceChildren(); });
it('selects files by keyboard and sends a stable escaped file reference, keeping bot mentions', async()=> {
 const send = vi.fn(async(_action: {text: string})=>{});
 setComposerHost({send, searchFiles: async()=>({files:[{path:'src/a b.ts',url:'file:///project/src/a%20b.ts'}],limited:false}), previewFile: async()=>({text:'<script>alert(1)</script>',status:'text'})});
 composer = new Composer(document.body);
 composer.update({botID:'A',botName:'A',messages:[],working:false,avatar:'',placeholder:'',replyingTo:null,pendingFiles:[],components:{},mentions:['Claude'],allMentions:['Claude']} as ChatState);
 composer.setText('@a'); composer.view.dispatch({selection:{anchor:2}});
 await vi.waitFor(()=>expect(document.querySelector('.mention-file')).not.toBeNull());
 await vi.waitFor(()=>expect(document.querySelector('.file-preview')?.textContent).toContain('<script>'));
 expect(document.querySelector('.file-preview script')).toBeNull();
 composer.view.contentDOM.dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',bubbles:true}));
 expect(composer.view.state.doc.toString()).toContain('file:///project/src/a%20b.ts');
 composer.submit();
 await vi.waitFor(()=>expect(send).toHaveBeenCalled());
 expect(send.mock.calls[0]?.[0]).toMatchObject({text:'[src/a b.ts](file:///project/src/a%20b.ts) '});
 composer.setText('@Cl'); composer.view.dispatch({selection:{anchor:3}});
 expect(document.querySelector('.mention-name')?.textContent).toBe('@Claude');
 composer.view.contentDOM.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}));
 expect((document.querySelector('.mention-list') as HTMLElement).hidden).toBe(true);
});
it('works with no bots, supports pointer and arrow selection, and ignores late results after Escape', async()=> {
 const search = vi.fn(async()=>({files:[{path:'one.ts',url:'file:///project/one.ts'},{path:'two.ts',url:'file:///project/two.ts'}],limited:false}));
 setComposerHost({send:async()=>{},searchFiles:search,previewFile:async()=>({text:'const safe = 1;',status:'text'})});
 composer=new Composer(document.body);
 composer.update({botID:'A',botName:'A',messages:[],working:false,avatar:'',placeholder:'',replyingTo:null,pendingFiles:[],components:{}} as ChatState);
 composer.setText('@');composer.view.dispatch({selection:{anchor:1}});
 await vi.waitFor(()=>expect(document.querySelectorAll('.mention-file')).toHaveLength(2));
 composer.view.contentDOM.dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowDown',bubbles:true}));
 expect(document.querySelector('.mention-file.active')?.textContent).toContain('two.ts');
 composer.view.contentDOM.dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowUp',bubbles:true}));
 document.querySelectorAll('.mention-file')[1].dispatchEvent(new MouseEvent('mousedown',{bubbles:true,cancelable:true}));
 expect(composer.text).toBe('[two.ts](file:///project/two.ts) ');
 expect(composer.view.state.selection.main.head).toBe(composer.text.length);
 expect(composer.view.hasFocus).toBe(true);
 composer.setText('@x');composer.view.dispatch({selection:{anchor:2}});
 composer.view.contentDOM.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}));
 await new Promise(resolve=>setTimeout(resolve,180));
 expect((document.querySelector('.mention-list') as HTMLElement).hidden).toBe(true);
});
it('does not show a previous chat’s delayed search in the current chat', async()=>{
 let finish!: (value:{files:{path:string;url:string}[];limited:boolean})=>void;
 setComposerHost({send:async()=>{},searchFiles:()=>new Promise(resolve=>{finish=resolve;})});
 composer=new Composer(document.body);
 const state=(botID:string)=>({botID,botName:botID,messages:[],working:false,avatar:'',placeholder:'',replyingTo:null,pendingFiles:[],components:{}} as ChatState);
 composer.update(state('A'));composer.setText('@file');composer.view.dispatch({selection:{anchor:5}});
 await vi.waitFor(()=>expect(finish).toBeTypeOf('function'));
 composer.update(state('B'));
 finish({files:[{path:'private-to-A.ts',url:'file:///A/private-to-A.ts'}],limited:false});
 await new Promise(resolve=>setTimeout(resolve,0));
 expect(document.querySelector('.mention-file')).toBeNull();expect(composer.text).toBe('');
});
