export type { OwnKey };

/** Both languages' tables (for the test that they match). */
export const ownWords = { en, zhHant };

/** A word of this plugin's, in the chat page's language (`<html lang>`; English otherwise), `{name}` marks filled from `values`. */
export function own(key: OwnKey, values: Record<string, string | number> = {}): string {
  const table: Record<OwnKey, string | readonly [string, string]> = document.documentElement.lang === "zh-Hant" ? zhHant : en;
  const word = table[key] ?? en[key];
  const text = typeof word === "string" ? word : values.n === 1 ? word[0] : word[1];
  return text.replace(/\{(\w+)\}/g, (mark, name: string) => (name in values ? String(values[name]) : mark));
}

export function isOwn(key: string): key is OwnKey {
  return key in en;
}
